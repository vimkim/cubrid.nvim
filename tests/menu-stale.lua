local base = assert(vim.env.CUBRID_TEST_DIR)
local plugin = assert(vim.env.CUBRID_PLUGIN_ROOT)
local notices = {}
vim.notify = function(message) notices[#notices + 1] = message end
vim.cmd('filetype plugin indent on')
vim.opt.completeopt = { 'menuone', 'noselect' }
require('cubrid').setup({ server_path = plugin .. '/tests/delay-server.py' })
vim.cmd('edit ' .. vim.fn.fnameescape(base .. '/stale.csql'))
assert(vim.wait(12000, function()
  local clients = vim.lsp.get_clients({ name = 'cubrid', bufnr = 0 })
  return #clients == 1 and clients[1].initialized
end, 50))
local buf = vim.api.nvim_get_current_buf()
local function later(ms, fn)
  vim.defer_fn(function()
    local ok, err = xpcall(fn, debug.traceback)
    if not ok then io.stderr:write('FAIL stale menu: ' .. err .. '\n'); vim.cmd('cquit 6') end
  end, ms)
end
local function prepare()
  vim.api.nvim_buf_set_lines(buf, 0, -1, false, { 'SELect; -- keep', 'outside' })
  vim.api.nvim_win_set_cursor(0, { 1, 3 })
  vim.api.nvim_input('i<C-X><C-O>')
end
later(100, function()
  prepare()
  later(200, function()
    vim.api.nvim_input('X')
    later(1900, function()
      assert(vim.fn.pumvisible() == 0, 'stale response opened a menu')
      assert(vim.api.nvim_buf_get_lines(buf, 0, 1, false)[1] == 'SELXect; -- keep', 'intervening input lost')
      vim.api.nvim_input('<Esc>')
      later(100, function()
        prepare()
        later(200, function()
          require('cubrid').restart()
          vim.api.nvim_input('<Esc>')
          later(2000, function()
            assert(vim.fn.pumvisible() == 0, 'restarted client opened a stale menu')
            assert(vim.api.nvim_buf_get_lines(buf, 0, 1, false)[1] == 'SELect; -- keep', 'restart changed text')
            print('PASS delayed edit and restart')
            assert(vim.wait(12000, function()
              local clients = vim.lsp.get_clients({ name = 'cubrid', bufnr = buf })
              return #clients == 1 and clients[1].initialized and vim.bo[buf].omnifunc:find('cubrid.completion', 1, true) ~= nil
            end, 50), 'restarted client did not attach')
            prepare()
            later(2000, function()
              assert(vim.fn.pumvisible() == 1, 'menu for intervening edit did not appear')
              vim.api.nvim_buf_set_lines(buf, 1, 2, false, { 'changed outside' })
              later(250, function()
                assert(vim.fn.pumvisible() == 0, 'menu not cancelled after unrelated edit')
                assert(vim.api.nvim_buf_get_lines(buf, 0, -1, false)[2] == 'changed outside', 'outside edit lost')
                assert(#notices > 0, 'cancelled completion was not reported')
                vim.api.nvim_input('<Esc>')
                later(100, function()
                  prepare()
                  later(200, function()
                    vim.api.nvim_input('<Esc>')
                    later(100, function()
                      vim.cmd('enew')
                      later(1800, function()
                        assert(vim.fn.pumvisible() == 0, 'old buffer opened a menu')
                        assert(vim.api.nvim_buf_get_lines(buf, 0, 1, false)[1] == 'SELect; -- keep', 'buffer switch changed text')
                        print('PASS menu edit and buffer switch')
                        vim.cmd('buffer ' .. buf)
                        prepare()
                        later(200, function()
                          vim.api.nvim_input('E<C-X><C-O>')
                          later(1900, function()
                            assert(vim.fn.pumvisible() == 1, 'newer completion did not open')
                            local menu = vim.fn.complete_info({ 'items' })
                            assert(#menu.items == 1 and menu.items[1].word == 'SELECT', 'newer completion has wrong items')
                            vim.api.nvim_input('<C-N><C-Y><Esc>')
                            later(200, function()
                              assert(vim.api.nvim_get_current_line() == 'SELECT; -- keep', 'newer completion did not apply')
                              print('PASS overlapping requests')
                              vim.cmd('qa!')
                            end)
                          end)
                        end)
                      end)
                    end)
                  end)
                end)
              end)
            end)
          end)
        end)
      end)
    end)
  end)
end)
