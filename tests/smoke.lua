local function eq(a, b, label)
  assert(vim.deep_equal(a, b), label .. ': ' .. vim.inspect(a) .. ' ~= ' .. vim.inspect(b))
end
vim.cmd('filetype plugin indent on')
vim.cmd('syntax on')
require('cubrid').setup({ server_path = '/missing/cubrid-language-server' })
vim.cmd('edit test.CSQL')
eq(vim.bo.filetype, 'cubrid', 'case insensitive filetype')
eq(vim.bo.commentstring, '-- %s', 'commentstring')
assert(vim.bo.indentexpr ~= '', 'indent configured')
vim.bo.shiftwidth = 2
vim.api.nvim_buf_set_lines(0, 0, -1, false, { 'BEGIN', 'SELECT 1;', 'END' })
vim.cmd('normal! gg=G')
eq(vim.fn.indent(2), 2, 'indent inside begin')
eq(vim.fn.indent(3), 0, 'dedent end')
vim.cmd('execute b:undo_ftplugin')
eq(vim.bo.commentstring, vim.go.commentstring, 'undo ftplugin')
vim.cmd('execute b:undo_indent')
eq(vim.bo.indentexpr, vim.go.indentexpr, 'undo indent')
vim.bo.modified = false
vim.cmd('edit generic.sql')
assert(vim.bo.filetype ~= 'cubrid', 'sql excluded')
require('cubrid').setup({ server_path = '/missing/cubrid-language-server', sql = true })
vim.cmd('edit opted.sql')
eq(vim.bo.filetype, 'cubrid', 'sql opt in')
local ok = pcall(require('cubrid').setup, { parser_worker = '/tmp/a' })
assert(not ok, 'partial native pair rejected')
assert(not pcall(require('cubrid').setup, false), 'invalid options rejected')
assert(not pcall(require('cubrid').setup, {parser_worker='/tmp/a', runtime_prefix='/tmp/b', worker_timeout=0/0}), 'invalid timeout rejected')
print('smoke passed')
vim.cmd('qa!')
