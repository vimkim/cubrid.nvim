local dir = assert(vim.env.CUBRID_TEST_DIR)
local server = vim.env.CUBRID_TEST_SERVER or '/home/vimkim/gh/cubrid-language-tools/.venv/bin/cubrid-language-server'
local notes = {}
vim.notify = function(message, level) assert(level == vim.log.levels.WARN, 'conflicts use WARN severity'); table.insert(notes, message) end
local function wait(f, label) assert(vim.wait(12000, f, 20), label) end
local function settle() vim.wait(250) end
local function count(s)
  local n = 0
  for _, note in ipairs(notes) do if note:find(s, 1, true) then n = n + 1 end end
  return n
end
vim.cmd('filetype plugin indent on')
vim.cmd('edit ' .. vim.fn.fnameescape(dir .. '/before.sql'))
assert(vim.bo.filetype == 'sql')
local cubrid = require('cubrid')
vim.cmd('edit ' .. vim.fn.fnameescape(dir .. '/preexisting.csql'))
vim.bo.filetype = 'cubrid'
local pre = assert(vim.lsp.start({name='preexisting-test', cmd={server}, root_dir=dir}, {bufnr=0, reuse_client=function() return false end}))
wait(function() return vim.lsp.get_client_by_id(pre).initialized end, 'preexisting client initialized')
cubrid.setup({ server_path = server })
wait(function() return count('preexisting-test') == 1 end, 'preexisting client warning')
settle()
assert(count('filetype') == 0, 'late setup leaves existing SQL quiet')
vim.cmd('edit ' .. vim.fn.fnameescape(dir .. '/default.SQL'))
assert(vim.bo.filetype == 'cubrid', 'SQL enabled by default')
wait(function() return #vim.lsp.get_clients({name='cubrid', bufnr=0}) == 1 end, 'owned client')
settle()
assert(count('filetype') == 0, 'built-in SQL detection is quiet')
local buf = vim.api.nvim_get_current_buf()
local id = assert(vim.lsp.start({ name='foreign-test', cmd={server}, root_dir=dir }, {bufnr=buf, reuse_client=function() return false end}))
wait(function() return count('foreign-test') == 1 end, 'foreign client warning')
assert(notes[#notes]:find('id ' .. id, 1, true) and notes[#notes]:find('/default.SQL', 1, true) and notes[#notes]:find('diagnostics', 1, true), 'actionable client warning')
vim.api.nvim_exec_autocmds('LspAttach', {buffer=buf, data={client_id=id}})
settle()
assert(count('foreign-test') == 1, 'foreign client warning deduplicated')
assert(vim.lsp.get_client_by_id(id), 'foreign client remains running')
cubrid.restart()
wait(function() local clients=vim.lsp.get_clients({name='cubrid', bufnr=buf}); return #clients == 1 and clients[1].initialized end, 'owned client restarted')
assert(vim.lsp.buf_is_attached(buf, id), 'foreign client stays attached on restart')
cubrid.setup({server_path=server, file_extensions={'.csql'}})
vim.cmd('edit ' .. vim.fn.fnameescape(dir .. '/optout.sql'))
assert(vim.bo.filetype == 'sql', 'SQL opt out')
settle()
assert(count('filetype') == 0, 'opt-out SQL is quiet')
vim.cmd('edit ' .. vim.fn.fnameescape(dir .. '/still.CSQL'))
assert(vim.bo.filetype == 'cubrid', 'CSQL remains enabled')
cubrid.setup({server_path=server})
vim.filetype.add({filename = {[dir .. '/override.sql'] = 'other-test'}})
vim.cmd('edit ' .. vim.fn.fnameescape(dir .. '/override.sql'))
wait(function() return count('other-test') == 1 end, 'exact filename conflict')
assert(notes[#notes]:find('expected cubrid', 1, true) and notes[#notes]:find(dir .. '/override.sql', 1, true) and notes[#notes]:find('file_extensions', 1, true), 'actionable filetype notice')
vim.api.nvim_exec_autocmds('FileType', {buffer=0})
settle()
assert(count('other-test') == 1, 'filetype warning deduplicated')
vim.filetype.add({filename = {[dir .. '/disabled.sql'] = 'disabled-test'}})
vim.cmd('edit ' .. vim.fn.fnameescape(dir .. '/disabled.sql'))
cubrid.setup({server_path=server, file_extensions={'.csql'}})
settle()
assert(count('disabled-test') == 0, 'scheduled warning honors current config')
cubrid.setup({server_path=server, file_extensions={'.sql'}})
vim.filetype.add({filename = {[dir .. '/disabled.csql'] = 'disabled-csql-test'}})
vim.cmd('edit ' .. vim.fn.fnameescape(dir .. '/disabled.csql'))
settle()
assert(count('disabled-csql-test') == 0, 'disabled CSQL is quiet')
cubrid.setup({server_path=server, file_extensions={'.csql'}})
vim.filetype.add({filename = {[dir .. '/override.csql'] = 'other-csql-test'}})
vim.cmd('edit ' .. vim.fn.fnameescape(dir .. '/override.csql'))
wait(function() return count('other-csql-test') == 1 end, 'enabled CSQL conflict')
assert(notes[#notes]:find('file_extensions', 1, true), 'CSQL warning has selection advice')
vim.filetype.add({filename = {[dir .. '/scheduled.csql'] = 'scheduled-csql-test'}})
vim.cmd('edit ' .. vim.fn.fnameescape(dir .. '/scheduled.csql'))
cubrid.setup({server_path=server, file_extensions={'.sql'}})
settle()
assert(count('scheduled-csql-test') == 0, 'scheduled CSQL warning honors current config')
cubrid.setup({server_path=server})
vim.cmd('edit ' .. vim.fn.fnameescape(dir .. '/override.sql'))
vim.cmd('bwipeout!')
vim.cmd('edit ' .. vim.fn.fnameescape(dir .. '/override.sql'))
wait(function() return count('other-test') == 2 end, 'warning after buffer wipe')
assert(not pcall(cubrid.setup, {sql='true'}), 'legacy SQL option')
assert(vim.lsp.get_client_by_id(pre), 'preexisting client remains running')
vim.api.nvim_create_autocmd('BufNewFile', {pattern='*competing.SQL', callback=function(args) vim.bo[args.buf].filetype = 'competing-test' end})
vim.cmd('edit ' .. vim.fn.fnameescape(dir .. '/competing.SQL'))
wait(function() return count('competing-test') == 1 end, 'competing autocmd warning')
assert(notes[#notes]:find('/competing.SQL', 1, true), 'preserve filename case')
vim.lsp.get_client_by_id(pre):stop()
vim.lsp.get_client_by_id(id):stop()
print('SQL defaults and conflicts passed')
vim.cmd('qa!')
